"""Compute every derived value and write the files in ``generated/``.

Columns and order follow spec/ALGORITHMS.md. Every file starts with the header line named in
spec/VOCABULARY.md section 6, so nobody mistakes it for an authored file.
"""

from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path

from factmodel.core.projection import ProjectionResult, project_labels
from factmodel.core.scope import ScopeResult, compute_scope
from factmodel.model.types import Entity, EvidenceRecord, Profile

GENERATED_HEADER = "# generated by fact project - do not edit"
EMPTY = "-"


@dataclass(frozen=True)
class Derived:
    scope: ScopeResult
    projection: ProjectionResult


def derive(
    entities: Mapping[str, Entity], evidence: Mapping[str, EvidenceRecord], profile: Profile
) -> Derived:
    """Run scope closure, then projection (which reads the scope)."""
    scope = compute_scope(entities, evidence, profile.anchor_entity)
    return Derived(scope, project_labels(entities, evidence, profile, scope))


def _cell(value: str | None) -> str:
    return EMPTY if value in (None, "") else str(value)


def _table(columns: list[str], rows: list[list[str]]) -> str:
    lines = [GENERATED_HEADER, "\t".join(columns), *("\t".join(row) for row in rows)]
    return "\n".join(lines) + "\n"


def render(derived: Derived) -> dict[str, str]:
    """Return the text of every generated file, keyed by its name in ``generated/``."""
    labels = [
        [
            label.relationship,
            label.label,
            _cell(", ".join(f"{target}={value}" for target, value in label.targets)),
        ]
        for label in derived.projection.labels
    ]
    residue = [[row.relationship, row.target] for row in derived.projection.residue]
    scope = [
        [
            row.entity,
            row.subject_scope,
            _cell(row.basis),
            _cell(" > ".join(row.via)),
            "true" if row.reachable else "false",
        ]
        for row in derived.scope.rows.values()
    ]
    rejections = [[row.fact, row.reason] for row in derived.scope.rejections]
    return {
        "labels.tsv": _table(["relationship", "label", "targets"], labels),
        "residue.tsv": _table(["relationship", "target"], residue),
        "scope.tsv": _table(["entity", "subject_scope", "basis", "via", "reachable"], scope),
        "scope-rejections.tsv": _table(["fact", "reason"], rejections),
    }


def write(root: Path, files: Mapping[str, str]) -> list[Path]:
    """Write generated files under ``root/generated``; unchanged files are not rewritten."""
    out = root / "generated"
    out.mkdir(parents=True, exist_ok=True)
    changed = []
    for name, text in files.items():
        path = out / name
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            changed.append(path)
    return changed
