"""Probe generator, rendering per dialect, and the probe files of a model (WP1.7).

``generate`` turns model facts into probe documents (``kind: probe``), each with a stable ID,
the fact it tests, an expected range when there is one, and SQL in the source's dialect.
``render`` rewrites a probe's SQL for another dialect, or returns None when the dialect lacks
a construct the probe needs (``unsupported_on_dialect``); a probe is never rendered wrong.
"""

import re
from collections.abc import Mapping
from dataclasses import dataclass
from typing import Any

import sqlglot
from sqlglot import exp

from factmodel import vocabulary
from factmodel.core.drafts import slug
from factmodel.model import joins
from factmodel.model.types import Entity, Probe, Source
from factmodel.probes import build

GENERATED_HEADER = "# generated by fact probe generate - do not edit"


@dataclass(frozen=True)
class Skipped:
    fact: str
    reason: str


def nested_dialects() -> frozenset[str]:
    """Dialects that can read a nested path (``vocabulary-map:dialect_nested_paths``)."""
    return vocabulary.flag_map("dialect_nested_paths")


def known_dialects() -> list[str]:
    return sorted(set(vocabulary.text_map("engine_dialect").values()))


def probe_id(kind: str, *parts: str) -> str:
    return slug("-".join([kind, *parts])).replace("_", "-")


def _pairs(join: str, source: str, target: str) -> list[tuple[str, str]] | None:
    """(source field, target field) pairs of a join, or None when it is not that shape."""
    pairs = []
    for condition in join.split(" AND "):
        left, _, right = condition.partition(" = ")
        lent, _, lfield = left.partition(".")
        rent, _, rfield = right.partition(".")
        if (lent, rent) == (source, target):
            pairs.append((lfield, rfield))
        elif (lent, rent) == (target, source):
            pairs.append((rfield, lfield))
        else:
            return None
    return pairs


def _expression_queries(
    join: str, source: str, target: Entity, physical: str
) -> tuple[exp.Select, exp.Select | None]:
    """``join_match`` and ``fan_out`` for an expression join (D-017).

    Conjuncts that read one end only filter that end's rows. ``fan_out`` groups the target by
    the target side of each equality between the ends; a join that compares the ends in any
    other way gets no ``fan_out``.
    """
    on = joins.condition(join, source, target.id, "s", "t")
    split = joins.parts(join, source, target.id)
    source_filters = joins.aliased(split.source_filters, "s")
    target_filters = joins.aliased(split.target_filters, "t")
    # source columns that take part in the comparison must not be null for a row to count
    sides = [left for left, _ in split.pairs]
    sides += [o.this if source == target.id else o for o in split.other]
    keyed = {
        c.name
        for node in sides
        for c in node.find_all(exp.Column)
        if source == target.id or c.table == source
    }
    match = build.join_match_on(
        physical,
        target.physical_name,
        on,
        [build.column("s", k) for k in sorted(keyed)],
        source_filters,
        target_filters,
    )
    if not split.pairs or split.other:
        return match, None
    target_keys = joins.aliased(tuple(right for _, right in split.pairs), "t")
    return match, build.fan_out_on(target.physical_name, target_keys, target_filters)


def _doc(
    kind: str,
    pid: str,
    entity: str,
    fact: str,
    query: exp.Expr,
    dialect: str,
    expected: Mapping[str, Mapping[str, float]] | None,
    nested: bool,
) -> dict[str, Any]:
    doc: dict[str, Any] = {
        "kind": "probe",
        "id": pid,
        "probe_kind": kind,
        "entity": entity,
        "fact": fact,
    }
    if expected:
        doc["expected"] = {k: dict(v) for k, v in expected.items()}
    doc["dialect"] = dialect
    doc["sql"] = query.sql(dialect=dialect, identify=True)
    if nested:
        others = [d for d in known_dialects() if d not in nested_dialects()]
        doc["unsupported_on_dialect"] = others
        doc["note"] = "Reads a nested field; only dialects with nested paths can run it."
    return doc


def generate(
    entities: Mapping[str, Entity],
    sources: Mapping[str, Source],
    dialect_of: Mapping[str, str],
    default_dialect: str | None = None,
) -> tuple[list[dict[str, Any]], list[Skipped]]:
    """Probe documents for every entity of a source with a known dialect, sorted by ID.

    ``dialect_of`` maps a source ID to its sqlglot dialect; ``default_dialect`` serves entities
    that name no source.
    """
    probes: list[dict[str, Any]] = []
    skipped: list[Skipped] = []
    for entity_id in sorted(entities):
        entity = entities[entity_id]
        dialect = dialect_of.get(entity.source) if entity.source else default_dialect
        if dialect is None:
            skipped.append(Skipped(entity_id, "the entity names no source with a dialect"))
            continue
        name = entity.physical_name
        probes.append(
            _doc(
                "row_count",
                probe_id("row_count", entity_id),
                entity_id,
                entity_id,
                build.row_count(name),
                dialect,
                {"row_count": {"min": 1}},
                False,
            )
        )
        if entity.keys.primary:
            probes.append(
                _doc(
                    "key_duplicates",
                    probe_id("key_duplicates", entity_id),
                    entity_id,
                    entity_id,
                    build.key_duplicates(name, entity.keys.primary),
                    dialect,
                    {"duplicate_keys": {"max": 0}},
                    False,
                )
            )
        rule = entity.keys.current_row_rule
        keys = (entity.keys.unique or [entity.keys.primary])[0]
        if rule and keys:
            condition = sqlglot.condition(rule, dialect=dialect)
            probes.append(
                _doc(
                    "current_row_ties",
                    probe_id("current_row_ties", entity_id),
                    entity_id,
                    entity_id,
                    build.current_row_ties(name, keys, condition),
                    dialect,
                    {"tied_keys": {"max": 0}},
                    False,
                )
            )
        anchor = entity.anchor_reference
        if anchor is not None:
            nested = "." in anchor.field
            if nested and dialect not in nested_dialects():
                skipped.append(
                    Skipped(f"{entity_id}.{anchor.field}", "nested field on this dialect")
                )
            else:
                probes.append(
                    _doc(
                        "null_rate",
                        probe_id("null_rate", entity_id, anchor.field),
                        entity_id,
                        f"{entity_id}.{anchor.field}",
                        build.null_rate(name, anchor.field),
                        dialect,
                        None,
                        nested,
                    )
                )
        for fld in entity.fields:
            if not fld.values:
                continue
            nested = "." in fld.address
            if nested and dialect not in nested_dialects():
                skipped.append(
                    Skipped(f"{entity_id}.{fld.address}", "nested field on this dialect")
                )
                continue
            probes.append(
                _doc(
                    "value_set",
                    probe_id("value_set", entity_id, fld.address),
                    entity_id,
                    f"{entity_id}.{fld.address}",
                    build.value_set(name, fld.address, fld.values),
                    dialect,
                    {"outside_values": {"max": 0}, "outside_rows": {"max": 0}},
                    nested,
                )
            )
        for rel in entity.relationships:
            ref = f"{entity_id}.{rel.key}"
            if rel.is_target_set or rel.status is not None or not isinstance(rel.join, str):
                skipped.append(Skipped(ref, "target sets and unresolved links get no probe in v1"))
                continue
            target = entities.get(rel.targets[0])
            if target is None:
                skipped.append(Skipped(ref, "the target entity is not in the model"))
                continue
            parsed = joins.parse(rel.join)
            if parsed.expression:
                try:
                    match, fan = _expression_queries(rel.join, entity_id, target, name)
                except joins.JoinError as error:
                    skipped.append(Skipped(ref, str(error)))
                    continue
                nested = False
            else:
                pairs = _pairs(rel.join, entity_id, rel.targets[0])
                if pairs is None:
                    skipped.append(Skipped(ref, "the join is not an equality between the two ends"))
                    continue
                nested = any("." in a or "." in b for a, b in pairs)
                if nested and dialect not in nested_dialects():
                    skipped.append(Skipped(ref, "nested field on this dialect"))
                    continue
                match = build.join_match(name, target.physical_name, pairs)
                fan = build.fan_out(target.physical_name, [b for _, b in pairs])
            probes.append(
                _doc(
                    "join_match",
                    probe_id("join_match", entity_id, rel.key),
                    entity_id,
                    ref,
                    match,
                    dialect,
                    {"orphans_left": {"max": 0}},
                    nested,
                )
            )
            if rel.cardinality in ("many_to_one", "one_to_one") and fan is not None:
                probes.append(
                    _doc(
                        "fan_out",
                        probe_id("fan_out", entity_id, rel.key),
                        entity_id,
                        ref,
                        fan,
                        dialect,
                        {"max_fan_out": {"max": 1}},
                        nested,
                    )
                )
    return sorted(probes, key=lambda p: p["id"]), skipped


def render(probe: Probe, dialect: str) -> str | None:
    """The probe's SQL in ``dialect``, or None when the probe is unsupported there."""
    if dialect in (probe.unsupported_on_dialect or []):
        return None
    tree = sqlglot.parse_one(probe.sql, read=probe.dialect)
    return tree.sql(dialect=dialect, identify=True)


def metrics(probe: Probe) -> list[str]:
    """The measurement keys the probe returns, from its outer select."""
    tree = sqlglot.parse_one(probe.sql, read=probe.dialect)
    if not isinstance(tree, exp.Select):
        return list(build.METRICS[probe.probe_kind])
    return [e.alias_or_name for e in tree.selects]


def _json_object_pairs(sql: str, keys: list[str]) -> str:
    pairs = ", ".join(f"'{k}', \"{k}\"" for k in keys)
    return f"SELECT json_object({pairs}) FROM ({sql}) AS q"


def _row_to_json(sql: str, keys: list[str]) -> str:
    return f"SELECT row_to_json(q) FROM ({sql}) AS q"


# The wrap strategies the code implements; which dialect uses which is vocabulary.
WRAPS = {"json_object_pairs": _json_object_pairs, "row_to_json": _row_to_json}


def json_wrapped(probe: Probe, dialect: str) -> str | None:
    """The rendered SQL wrapped to print one JSON object, per ``dialect_json_wrap``.

    A dialect without a wrap strategy gets the plain SQL; its runner must print JSON itself.
    """
    sql = render(probe, dialect)
    if sql is None:
        return None
    strategy = vocabulary.text_map("dialect_json_wrap").get(dialect)
    if strategy is None:
        return sql
    if strategy not in WRAPS:
        raise ValueError(f"dialect_json_wrap names unknown strategy {strategy!r} for {dialect}")
    return WRAPS[strategy](sql, metrics(probe))


