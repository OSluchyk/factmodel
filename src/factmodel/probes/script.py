"""Plain shell scripts for owner-run probes (``fact probe render``).

A script holds every probe of one source in one dialect, so the owner can read the SQL before
running it. It prints JSON lines that ``fact probe intake`` reads: a header, then one line per
probe. ``RUN_SQL`` is the command that reads one statement on stdin and prints one JSON object;
the vocabulary blocks ``dialect_json_wrap`` and ``dialect_runner`` give the wrapping and a default
command per dialect; any other dialect needs ``RUN_SQL`` set.
"""

from factmodel import vocabulary
from factmodel.model.types import Probe
from factmodel.probes import json_wrapped

HEADER = "# generated by fact probe render - do not edit"


def _quote(text: str) -> str:
    return "'" + text.replace("'", "'\"'\"'") + "'"


def script(source_id: str, dialect: str, probes: list[Probe]) -> tuple[str, list[str]]:
    """The script text, and the IDs of probes left out because the dialect lacks a construct."""
    default = vocabulary.text_map("dialect_runner").get(dialect)
    run_sql = (
        f'RUN_SQL="${{RUN_SQL:-{default}}}"'
        if default
        else 'RUN_SQL="${RUN_SQL:?set RUN_SQL to a command that prints one JSON object per query}"'
    )
    lines = [
        "#!/usr/bin/env bash",
        HEADER,
        f"# Probes for source {source_id} in dialect {dialect}: counts only, never values.",
        "# Read the SQL before running. Output: JSON lines, a header then one line per probe.",
        "# Save it to a file and run: fact probe intake <file>",
        "set -uo pipefail",
        run_sql,
        'PIN="${PIN:?set PIN to <engine>:<target>@<YYYY-MM-DD>}"',
        'ENVIRONMENT="${ENVIRONMENT:-prod}"',
        'DATA_QUALITY="${DATA_QUALITY:-unknown}"',
        'RAN_ON="${RAN_ON:-$(date +%F)}"',
        'printf \'{"source": "%s", "pin": "%s", "environment": "%s", '
        '"data_quality": "%s", "ran_on": "%s"}\\n\' '
        f'{_quote(source_id)} "$PIN" "$ENVIRONMENT" "$DATA_QUALITY" "$RAN_ON"',
        "run_probe() {",
        '  local id="$1" out',
        '  if out=$(printf "%s" "$2" | bash -c "$RUN_SQL" 2>/dev/null) && [ -n "$out" ]; then',
        '    printf \'{"probe": "%s", "measurement": %s}\\n\' "$id" "$out"',
        "  else",
        '    printf \'{"probe": "%s", "error": "QUERY FAILED"}\\n\' "$id"',
        '    echo "QUERY FAILED: $id" >&2',
        "  fi",
        "}",
    ]
    skipped = []
    for probe in sorted(probes, key=lambda p: p.id):
        sql = json_wrapped(probe, dialect)
        if sql is None:
            skipped.append(probe.id)
            lines.append(f"# {probe.id}: not rendered, {dialect} lacks a construct it needs")
            continue
        lines.append(f"run_probe {_quote(probe.id)} {_quote(sql)}")
    return "\n".join(lines) + "\n", skipped
