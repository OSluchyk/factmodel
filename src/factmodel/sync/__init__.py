"""``fact sync``: compare the latest snapshot of a source with the previous one and the model.

New facts become drafts in ``drafts/`` (never ``physical/``), lost facts open findings, changed
facts are listed for their evidence to be renewed, and a moved pin fires ``source_pin_moved``
triggers. Everything is written only when it changes, so a second run produces no diff.
"""

import io
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ruamel.yaml import YAML

from factmodel.core.drafts import to_facts
from factmodel.io.yaml_strict import load
from factmodel.model.loader import inspect_model
from factmodel.model.types import Finding, Snapshot, Trigger
from factmodel.sync.drift import DriftItem, drift

DRIFT_HEADER = "<!-- generated by fact sync - do not edit -->"


@dataclass
class SyncResult:
    items: list[DriftItem]
    written: list[Path] = field(default_factory=list)


def snapshots(root: Path, source_id: str) -> list[Path]:
    return sorted((root / "sources" / "snapshots").glob(f"{source_id}@*.yaml"))


def _snapshot(path: Path) -> Snapshot:
    return Snapshot.model_validate(load(path).data)


def _write(path: Path, text: str, written: list[Path]) -> None:
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    written.append(path)


def _dump(doc: Any) -> str:
    yaml = YAML(typ="safe", pure=True)
    yaml.default_flow_style = False
    yaml.sort_base_mapping_type_on_output = False  # type: ignore[assignment]
    buf = io.StringIO()
    yaml.dump(doc, buf)
    return buf.getvalue()


def report(
    source_id: str, previous: Snapshot | None, latest: Snapshot, items: list[DriftItem]
) -> str:
    lines = [
        DRIFT_HEADER,
        f"# Drift for source `{source_id}`",
        "",
        f"- Previous: `{previous.pin if previous and previous.pin else 'none'}`",
        f"- Latest: `{latest.pin or latest.taken_on}`",
        "",
    ]
    if not items:
        return "\n".join([*lines, "No drift.", ""])
    lines += [
        "| Object | Field | Kind | Class | Entity | Detail |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for item in items:
        cells = [item.object, item.field or "-", item.kind, item.drift_class, item.entity or "-"]
        lines.append("| " + " | ".join([*cells, item.detail or "-"]) + " |")
    return "\n".join([*lines, ""])


def _next_finding(findings: list[Finding]) -> int:
    numbers = [int(f.id[2:]) for f in findings]
    return max(numbers, default=0) + 1


def _findings(root: Path, items: list[DriftItem], day: str, written: list[Path]) -> None:
    model = inspect_model(root).model
    existing = list(model.findings.values())
    keys = {
        str(f.extensions.get("sync_key"))
        for f in existing
        if f.extensions and "sync_key" in f.extensions
    }
    number = _next_finding(existing)
    for item in items:
        if item.drift_class != "lost_fact" or item.key in keys:
            continue
        target = item.entity or item.object
        what = f"field {item.field}" if item.field else "object"
        doc = {
            "kind": "finding",
            "id": f"F-{number:04d}",
            "title": f"Lost {what} on {item.object}",
            "status": "open",
            "opened_on": day,
            "about": [target] if item.entity else None,
            "description": f"fact sync: {item.key}; the model still describes it.",
            "extensions": {"sync_key": item.key},
        }
        doc = {k: v for k, v in doc.items() if v is not None}
        _write(root / "registers" / "findings" / f"F-{number:04d}.yaml", _dump(doc), written)
        keys.add(item.key)
        number += 1


def _fire(
    root: Path,
    source_id: str,
    previous: Snapshot | None,
    latest: Snapshot,
    day: str,
    written: list[Path],
) -> None:
    if previous is None or previous.pin is None or previous.pin == latest.pin:
        return
    detail = f"{source_id} moved from {previous.pin} to {latest.pin}"
    for f in inspect_model(root).model.files:
        if not isinstance(f.obj, Trigger) or f.obj.event != "source_pin_moved":
            continue
        if any(firing.detail == detail for firing in f.obj.fired or []):
            continue
        path = root / f.path
        yaml = YAML(typ="rt")
        doc = yaml.load(path.read_text(encoding="utf-8"))
        doc.setdefault("fired", []).append({"on": day, "detail": detail})
        buf = io.StringIO()
        yaml.dump(doc, buf)
        _write(path, buf.getvalue(), written)


def sync(root: Path, source_id: str) -> SyncResult:
    paths = snapshots(root, source_id)
    if not paths:
        raise ValueError(f"no snapshot for source {source_id!r}; run fact snapshot first")
    latest = _snapshot(paths[-1])
    previous = _snapshot(paths[-2]) if len(paths) > 1 else None
    model = inspect_model(root).model
    items = drift(previous, latest, model.entities)
    result = SyncResult(items)
    new_objects = {i.object for i in items if i.drift_class == "new_fact"}
    for draft in to_facts(latest):
        if draft.document["physical_name"] in new_objects:
            _write(root / draft.path, _dump(draft.document), result.written)
    day = latest.taken_on
    _findings(root, items, day, result.written)
    _fire(root, source_id, previous, latest, day, result.written)
    name = re.sub(r"[^A-Za-z0-9_.-]", "_", source_id)
    _write(
        root / "generated" / f"drift-{name}.md",
        report(source_id, previous, latest, items),
        result.written,
    )
    return result
